export type WritingProfile = keyof typeof writingProfiles;
export function resolveWritingProfile(
  kind: "page" | "post",
  profile?: WritingProfile,
): WritingProfile {
  return profile && writingProfiles[profile]?.kind === kind
    ? profile
    : kind === "post"
      ? "guide"
      : "reference";
}
